static void load_config(void) {
    input_default_pads(cfg.pad);
    FILE *f = nes_fopen(ini_path, "r");
    if (!f) return;
    char line[2400];
    while (fgets(line, sizeof line, f)) {
        char *eq = strchr(line, '=');
        if (!eq || line[0] == ';' || line[0] == '#') continue;
        *eq = 0;
        char *key = trim(line), *val = eq + 1;
        /* a ';' starts a comment except inside the rom path */
        if (strcmp(key, "rom") != 0) { char *c = strpbrk(val, ";#"); if (c) *c = 0; }
        val = trim(val);
        for (char *p = key; *p; p++) *p = (char)tolower((unsigned char)*p);
        int handled = 0;
        for (int i = 0; i < K_TOTAL; i++) {
            if (!strcmp(key, key_names[i])) {
                char buf[64]; snprintf(buf, sizeof buf, "%s", val);
                if (strlen(buf) == 1) buf[0] = (char)tolower((unsigned char)buf[0]);
                SDL_Keycode k = SDL_GetKeyFromName(buf);
                if (k != SDLK_UNKNOWN) cfg.key[i] = (int)k;
                handled = 1;
            } else if (!strncmp(key, "pad_", 4) && !strcmp(key + 4, key_names[i])) {
                cfg.pad[i] = input_pad_from_name(val);
                handled = 1;
            }
        }
        if (handled) continue;
        if (!strcmp(key, "rom")) snprintf(cfg.rom, sizeof cfg.rom, "%s", val);
        else if (!strcmp(key, "window_size")) { int v = atoi(val); if (v >= 1 && v <= 6) cfg.window_size = v; }
        else if (!strcmp(key, "display_mode")) { int v = atoi(val); if (v >= 0 && v <= 2) cfg.display_mode = v; }
        else if (!strcmp(key, "resolution")) { int v = atoi(val); if (v >= 0 && v < N_RESOLUTIONS) cfg.resolution = v; }
        else if (!strcmp(key, "scaling")) { int v = atoi(val); if (v >= 0 && v <= 2) cfg.scaling = v; }
        else if (!strcmp(key, "aspect")) { int v = atoi(val); if (v >= 0 && v <= 3) cfg.aspect = v; }
        else if (!strcmp(key, "filter")) { int v = atoi(val); if (v >= 0 && v <= 2) cfg.filter = v; }
        else if (!strcmp(key, "shader")) { int v = atoi(val); if (v >= 0 && v <= 4) cfg.shader = v; }
        else if (!strcmp(key, "shader_strength")) { int v = atoi(val); if (v >= 0 && v <= 2) cfg.shader_strength = v; }
        else if (!strcmp(key, "overscan")) cfg.overscan = atoi(val) ? 1 : 0;
        else if (!strcmp(key, "no_sprite_limit")) cfg.no_sprite_limit = atoi(val) ? 1 : 0;
        else if (!strcmp(key, "rewind_enabled")) cfg.rewind = atoi(val) ? 1 : 0;
        else if (!strcmp(key, "state_slot")) { int v = atoi(val); if (v >= 1 && v <= 9) cfg.state_slot = v; }
        else if (!strcmp(key, "ra_hardcore")) cfg.ra_hardcore = atoi(val) ? 1 : 0;
        else if (!strcmp(key, "low_latency")) cfg.lowlat = atoi(val) ? 1 : 0;
        else if (!strcmp(key, "runahead")) { int v = atoi(val); if (v >= 0 && v <= 3) cfg.runahead = v; }
        else if (!strcmp(key, "audio_latency")) { int v = atoi(val); if (v >= 0 && v <= 2) cfg.audio_latency = v; }
        else if (!strcmp(key, "volume")) { int v = atoi(val); if (v >= 0 && v <= 100) cfg.volume = v; }
        else if (!strcmp(key, "scale")) { int v = atoi(val); if (v >= 1 && v <= 6) cfg.window_size = v; }
    }
    fclose(f);
    window_size_idx = cfg.window_size - 1;
}

