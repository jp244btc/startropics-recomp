static void set_rom_name(const char *path) {
    const char *base = path;
    for (const char *p = path; *p; p++) if (*p == '/' || *p == '\\') base = p + 1;
    snprintf(rom_name, sizeof rom_name, "%s", base);
    char *dot = strrchr(rom_name, '.');
    if (dot) *dot = 0;
}

static void refresh_rom_items(void);

/* loads and verifies a cartridge dump; returns 1 when it is a StarTropics ROM */
static int load_rom_file(const char *path) {
    rom_ok = 0; game_started = 0;
    if (!path || !*path) { snprintf(rom_status, sizeof rom_status, "No ROM selected"); refresh_rom_items(); return 0; }
    if (!file_exists(path)) { snprintf(rom_status, sizeof rom_status, "File not found"); refresh_rom_items(); return 0; }
    if (nes_load(path) != 0) {
        snprintf(rom_status, sizeof rom_status, "Not a valid .nes file");
        refresh_rom_items();
        return 0;
    }
    const char *known = cart_known_name();
    int native = recomp_rom_sha1 && strcmp(recomp_rom_sha1, cart.sha1_hex) == 0;
    snprintf(rom_hashes, sizeof rom_hashes, "SHA-1 %s  MD5 %s  CRC32 %08X", cart.sha1_hex, cart.md5_hex, cart.crc32);
    if (!known && !native) {
        snprintf(rom_status, sizeof rom_status, "Hash check FAILED: not a known StarTropics dump (%s)", rom_hashes);
        refresh_rom_items();
        return 0;
    }
    sys.use_recomp = native != 0;
    rom_ok = 1;
    set_rom_name(path);
    snprintf(state_dir, sizeof state_dir, "%ssaves", data_dir);
    make_dir(state_dir);
    snprintf(sav_path, sizeof sav_path, "%s/%s.sav", state_dir, rom_name);
    {
        /* a save state from before the slots becomes slot 1 */
        char old[2048], slot1[2048];
        snprintf(old, sizeof old, "%s/%s.state", state_dir, rom_name);
        slot_path(1, slot1, sizeof slot1);
        if (file_exists(old) && !file_exists(slot1) && move_file(old, slot1) == 0) printf("moved %s to slot 1\n", old);
    }
    if (cart.battery && cart_load_battery(sav_path) == 0) printf("battery RAM loaded from %s\n", sav_path);
    memcpy(wram_snapshot, cart.wram, cart_battery_size());
    if (native) snprintf(rom_status, sizeof rom_status, "%s: hash check passed, running native code", known ? known : "StarTropics");
    else snprintf(rom_status, sizeof rom_status, "%s: hash check passed, interpreter mode (native code is for the USA version)", known);
    {
        char full[2048];
        absolute_path(path, full, sizeof full);
        if (strcmp(cfg.rom, full) != 0) { snprintf(cfg.rom, sizeof cfg.rom, "%s", full); write_config(); }
        ach_load_game(full, known ? known : "StarTropics");
    }
    rewind_clear();
    ach_reset();
    printf("ROM: %s (%s) %s | mode: %s | data folder: %s\n", rom_name, known ? known : "unknown", rom_hashes,
           sys.use_recomp ? "native (recompiled)" : "interpreter", data_dir);
    fflush(stdout);
    update_title();
    refresh_rom_items();
    audio_out_clear();
    return 1;
}

