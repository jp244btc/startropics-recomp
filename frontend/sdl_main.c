/* Decide how frames are paced. On a display whose refresh is a multiple of
   ~60 Hz the loop is phase-locked to its vertical blank (one game frame per
   vblank, or per two vblanks on 120 Hz), presenting just before each one, and
   the audio's rate control absorbs the 0.16% speed difference. Otherwise the
   loop is paced by the timer with vsync off. */
static void setup_sync(void) {
    SDL_DisplayMode m;
    refresh_hz = 0;
    if (SDL_GetWindowDisplayMode(window, &m) == 0 && m.refresh_rate > 0) refresh_hz = m.refresh_rate;
    pace_mode = 0; vsync_div = 1;
    if (cfg.lowlat && refresh_hz > 0) {
        int div = (int)(refresh_hz / 60.0 + 0.5);
        if (div < 1) div = 1;
        double per = refresh_hz / div;
        if (fabs(per - NES_FPS) / NES_FPS < 0.025) {
            vsync_div = div;
            if (gpu_sync_vblank_init(window)) pace_mode = 1;
            else if (SDL_RenderSetVSync(renderer, 1) == 0) pace_mode = 2;
        }
    }
    if (pace_mode != 2) SDL_RenderSetVSync(renderer, 0);
}

/* the window's client size: the chosen resolution, else the game picture at the window-size multiple */
static void window_size_for_config(int *w, int *h) {
    if (cfg.resolution > 0 && cfg.resolution < N_RESOLUTIONS) { *w = resolutions[cfg.resolution].w; *h = resolutions[cfg.resolution].h; return; }
    SDL_Rect src; source_rect(&src);
    *h = src.h * cfg.window_size;
    *w = (int)(*h * target_aspect(src.h) + 0.5);
}

static void apply_graphics(void) {
    cfg.window_size = window_size_idx + 1;
    ppu_no_sprite_limit = cfg.no_sprite_limit != 0;
    Uint32 flags = SDL_GetWindowFlags(window);
    int cur = ((flags & SDL_WINDOW_FULLSCREEN_DESKTOP) == SDL_WINDOW_FULLSCREEN_DESKTOP) ? 1 : (flags & SDL_WINDOW_FULLSCREEN) ? 2 : 0;
    if (cfg.display_mode == 2) {
        /* exclusive fullscreen: the chosen resolution as a real display mode when the display
           offers it, else the desktop mode (no mode switch, but the compositor is bypassed) */
        SDL_DisplayMode dm, want, got;
        int di = SDL_GetWindowDisplayIndex(window);
        if (SDL_GetDesktopDisplayMode(di, &dm) != 0) SDL_zero(dm);
        if (cfg.resolution > 0 && cfg.resolution < N_RESOLUTIONS) {
            want = dm; want.w = resolutions[cfg.resolution].w; want.h = resolutions[cfg.resolution].h;
            if (SDL_GetClosestDisplayMode(di, &want, &got)) dm = got;
        }
        if (dm.w) SDL_SetWindowDisplayMode(window, &dm);
        if (cur != 2) SDL_SetWindowFullscreen(window, SDL_WINDOW_FULLSCREEN);
    } else if (cur != cfg.display_mode) {
        SDL_SetWindowFullscreen(window, cfg.display_mode == 1 ? SDL_WINDOW_FULLSCREEN_DESKTOP : 0);
    }
    if (cfg.display_mode == 0) {
        int w, h, cw, ch;
        window_size_for_config(&w, &h);
        SDL_GetWindowSize(window, &cw, &ch);
        if (cw != w || ch != h) SDL_SetWindowSize(window, w, h);
    }
    setup_sync();
    write_config();
}

static void toggle_fullscreen(void) {
    cfg.display_mode = cfg.display_mode ? 0 : 1;
    apply_graphics();
}

/* sleep until the given performance-counter time, coarse SDL_Delay first, then a short spin */
static void sleep_until(double target_ticks, double tick_ms) {
    for (;;) {
        double now = (double)SDL_GetPerformanceCounter();
        double remaining_ms = (target_ticks - now) * tick_ms;
        if (remaining_ms <= 0.05) break;
        if (remaining_ms > 2.0) SDL_Delay(1);
        /* else spin */
    }
}

static int write_png_rgb32(const char *path, const uint32_t *px, int w, int h) {
    uint8_t *rgb = malloc((size_t)w * h * 3);
    for (int i = 0; i < w * h; i++) {
        rgb[i * 3] = (uint8_t)(px[i] >> 16); rgb[i * 3 + 1] = (uint8_t)(px[i] >> 8); rgb[i * 3 + 2] = (uint8_t)px[i];
    }
    int r = png_write_rgb(path, w, h, rgb);
    free(rgb);
    return r;
}

/* the picture as shown (full height; in widescreen mode the visible part of the wide frame) */
static int write_frame_png(const char *path) {
    frame_to_rgb();
    SDL_Rect src;
    source_rect(&src);
    uint32_t *px = malloc((size_t)src.w * FB_H * sizeof(uint32_t));
    for (int y = 0; y < FB_H; y++) memcpy(px + (size_t)y * src.w, frame_rgb + (size_t)y * frame_w + src.x, (size_t)src.w * sizeof(uint32_t));
    int r = write_png_rgb32(path, px, src.w, FB_H);
    free(px);
    return r;
}

/* screenshot of the whole window (used for the UI self-test) */
static int write_window_png(const char *path) {
    int ww, wh;
    SDL_GetRendererOutputSize(renderer, &ww, &wh);
    uint32_t *px = malloc((size_t)ww * wh * 4);
    if (SDL_RenderReadPixels(renderer, NULL, SDL_PIXELFORMAT_ARGB8888, px, ww * 4) != 0) { free(px); return -1; }
    int r = write_png_rgb32(path, px, ww, wh);
    free(px);
    return r;
}

