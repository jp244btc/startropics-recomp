static char *trim(char *s) {
    while (isspace((unsigned char)*s)) s++;
    char *e = s + strlen(s);
    while (e > s && isspace((unsigned char)e[-1])) *--e = 0;
    return s;
}

/* absolute path for the remembered ROM, so a relative path given on the command line survives a double-click launch */
static void absolute_path(const char *in, char *out, size_t n) {
#ifdef _WIN32
    wchar_t win[4096], wfull[4096];
    if (MultiByteToWideChar(CP_UTF8, 0, in, -1, win, 4096) && GetFullPathNameW(win, 4096, wfull, NULL) &&
        WideCharToMultiByte(CP_UTF8, 0, wfull, -1, out, (int)n, NULL, NULL)) return;
#else
    char *r = realpath(in, NULL);
    if (r) { snprintf(out, n, "%s", r); free(r); return; }
#endif
    snprintf(out, n, "%s", in);
}

/* Settings and saves live next to the executable when that folder can be written
   (portable use). Otherwise (Program Files, a read-only share, running straight
   from inside a zip) they go to the per-user application-data folder, so the
   chosen ROM is remembered either way. */
static void choose_data_dir(void) {
    char probe[1200];
    snprintf(probe, sizeof probe, "%s.write-test", base_dir);
    FILE *f = nes_fopen(probe, "wb");
    if (f) {
        fclose(f);
#ifdef _WIN32
        wchar_t w[1200];
        if (MultiByteToWideChar(CP_UTF8, 0, probe, -1, w, 1200)) _wremove(w);
#else
        remove(probe);
#endif
        snprintf(data_dir, sizeof data_dir, "%s", base_dir);
        return;
    }
    char *p = SDL_GetPrefPath("StarTropicsPort", "StarTropics");
    if (p) { snprintf(data_dir, sizeof data_dir, "%s", p); SDL_free(p); }
    else snprintf(data_dir, sizeof data_dir, "%s", base_dir);
}

