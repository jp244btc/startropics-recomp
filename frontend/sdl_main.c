static uint64_t fb_hash(void) {
    uint64_t h = 0xcbf29ce484222325ULL;
    for (size_t i = 0; i < sizeof ppu.fb; i++) { h ^= ppu.fb[i]; h *= 0x100000001b3ULL; }
    return h;
}

/* --rewind-test N: run N frames recording the picture of each and the rewind history every
   other frame, then step back through the whole history checking that every re-run frame
   matches what was recorded on the way forward */
static int rewind_selftest(int frames) {
    frames &= ~1;
    size_t sz = nes_state_size();
    void *st = malloc(sz);
    uint64_t *hashes = malloc(sizeof(uint64_t) * (size_t)(frames + 1));
    if (!rewind_init(sz, 8u << 20)) { printf("rewind-test: init failed\n"); return 1; }
    #define TEST_PAD(f) ((uint8_t)(((f) >= 150 && (f) < 160) || ((f) >= 400 && (f) < 410) ? 0x08 : ((f) >= 600 && (f) < 700) ? 0x80 : 0))
    for (int f = 1; f <= frames; f++) {
        nes_set_pad(0, TEST_PAD(f));
        nes_run_frame();
        hashes[f] = fb_hash();
        if ((f & 1) == 0) { nes_state_save(st, sz); rewind_push(st); }
    }
    size_t used = rewind_bytes_used();
    int steps = 0, ok = 1;
    for (int f = frames; f >= 4; f -= 2) {
        if (!rewind_pop(st)) { printf("rewind-test: history ended early at frame %d\n", f); ok = 0; break; }
        nes_state_load(st, sz);
        apu_flush_samples();
        nes_set_pad(0, TEST_PAD(f - 1));
        nes_run_frame();
        if (fb_hash() != hashes[f - 1]) { printf("rewind-test: frame %d differs after rewinding\n", f - 1); ok = 0; break; }
        steps++;
    }
    #undef TEST_PAD
    printf("rewind-test: %d frames forward, %d steps back %s; history %zu bytes (%.0f bytes per record)\n",
           frames, steps, ok ? "all matched" : "FAILED", used, (double)used / (frames / 2));
    rewind_shutdown();
    free(st); free(hashes);
    return ok ? 0 : 1;
}

