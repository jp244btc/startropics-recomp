static int file_mtime(const char *path, time_t *t) {
#ifdef _WIN32
    wchar_t w[2048];
    struct _stat st;
    if (!MultiByteToWideChar(CP_UTF8, 0, path, -1, w, 2048) || _wstat(w, &st) != 0) return 0;
#else
    struct stat st;
    if (stat(path, &st) != 0) return 0;
#endif
    *t = st.st_mtime;
    return 1;
}

static int move_file(const char *from, const char *to) {
#ifdef _WIN32
    wchar_t a[2048], b[2048];
    if (!MultiByteToWideChar(CP_UTF8, 0, from, -1, a, 2048) || !MultiByteToWideChar(CP_UTF8, 0, to, -1, b, 2048)) return -1;
    return _wrename(a, b);
#else
    return rename(from, to);
#endif
}

/* a message shown in the corner of the game for a couple of seconds (also printed) */
static void osd(const char *fmt, ...) {
    va_list ap;
    va_start(ap, fmt);
    vsnprintf(osd_text, sizeof osd_text, fmt, ap);
    va_end(ap);
    osd_until = SDL_GetTicks64() + 2200;
    printf("%s\n", osd_text);
}

