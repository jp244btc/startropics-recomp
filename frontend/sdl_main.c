/* save states: nine slots per ROM, saves/<rom name>.state1 .. .state9 */
static void slot_path(int slot, char *out, size_t n) { snprintf(out, n, "%s/%s.state%d", state_dir, rom_name, slot); }

static int slot_saved_at(int slot, char *when, size_t n) {
    char path[2048];
    time_t t;
    slot_path(slot, path, sizeof path);
    if (!file_mtime(path, &t)) return 0;
    strftime(when, n, "%Y-%m-%d %H:%M", localtime(&t));
    return 1;
}

static void state_save(void) {
    if (!rom_ok) return;
    char path[2048];
    slot_path(cfg.state_slot, path, sizeof path);
    size_t len = nes_state_size();
    void *buf = malloc(len);
    if (nes_state_save(buf, len) == 0) {
        FILE *f = nes_fopen(path, "wb");
        if (f) { fwrite(buf, 1, len, f); fclose(f); osd("State saved to slot %d", cfg.state_slot); }
        else osd("Could not write %s", path);
    }
    free(buf);
    refresh_play_items();
}

static int state_load(void) {
    if (!rom_ok) return 0;
    if (ach_hardcore()) { osd("Hardcore mode: save states cannot be loaded"); return 0; }
    char path[2048];
    slot_path(cfg.state_slot, path, sizeof path);
    size_t len = nes_state_size();
    void *buf = malloc(len);
    FILE *f = nes_fopen(path, "rb");
    if (!f) { osd("Slot %d is empty", cfg.state_slot); free(buf); return 0; }
    size_t n = fread(buf, 1, len, f);
    fclose(f);
    int ok = 0;
    if (n == len && nes_state_load(buf, len) == 0) {
        apu_flush_samples();      /* the sound queued before the load belongs to the old timeline */
        audio_out_clear();
        rewind_clear();
        game_started = 1;
        osd("State loaded from slot %d", cfg.state_slot);
        ok = 1;
    } else osd("Slot %d: the save state is from another version of the program", cfg.state_slot);
    free(buf);
    return ok;
}

static void select_slot(int slot) {
    if (slot < 1) slot = 9;
    if (slot > 9) slot = 1;
    cfg.state_slot = slot;
    char when[40];
    if (slot_saved_at(slot, when, sizeof when)) osd("Save state slot %d (saved %s)", slot, when);
    else osd("Save state slot %d (empty)", slot);
    refresh_play_items();
    write_config();
}

/* diagnostic: --list-controllers [file] (a GUI-subsystem exe cannot always print to a console) */
static void list_controllers(const char *out_path) {
    FILE *out = out_path ? nes_fopen(out_path, "w") : stdout;
    if (!out) out = stdout;
    int n = SDL_NumJoysticks();
    fprintf(out, "%d input device(s)\n", n);
    for (int i = 0; i < n; i++) {
        fprintf(out, "  %d: %s  [%s]\n", i, SDL_JoystickNameForIndex(i),
                SDL_IsGameController(i) ? "game controller mapping available" : "no mapping, generic joystick fallback");
        char *m = SDL_GameControllerMappingForDeviceIndex(i);
        if (m) { fprintf(out, "     %s\n", m); SDL_free(m); }
    }
    if (out != stdout) fclose(out);
}

